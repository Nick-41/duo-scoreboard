export function nameLines(value) {
  return value.split(/\r?\n/).map(line => line.trim()).filter(Boolean);
}

export function randomNickname(existing) {
  const used = new Set(existing.map(name => name.trim().normalize()));
  let name;
  do {
    const prefix = prefixes[randomIndex(prefixes.length)];
    const motif = randomIndex(4) === 0 ? '' : motifs[randomIndex(motifs.length)];
    const ending = endings[randomIndex(endings.length)];
    name = prefix + motif + ending;
  } while (used.has(name));
  return name;
}
