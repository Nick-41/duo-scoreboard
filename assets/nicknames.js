export function randomNickname(existing) {
  const usedModifiers = new Set();
  const usedNouns = new Set();

  for (const existingName of existing) {
    const name = existingName.trim().normalize();
    const matchingModifiers = modifiers.filter(word => name.startsWith(word));
    const exactModifier = matchingModifiers.find(word => nounSet.has(name.slice(word.length).trimStart()));
    if (exactModifier) {
      usedModifiers.add(exactModifier);
      usedNouns.add(name.slice(exactModifier.length).trimStart());
      continue;
    }
    // Older names and custom names can still share a word with the current pool.
    for (const word of matchingModifiers) usedModifiers.add(word);
    const leadingNoun = longestNounsFirst.find(word => name.startsWith(word));
    const trailingNoun = longestNounsFirst.find(word => name.endsWith(word));
    if (leadingNoun) usedNouns.add(leadingNoun);
    if (trailingNoun) usedNouns.add(trailingNoun);
  }

  const availableModifiers = modifiers.filter(word => !usedModifiers.has(word));
  const availableNouns = nouns.filter(word => !usedNouns.has(word));
  return availableModifiers[randomIndex(availableModifiers.length)] +
    availableNouns[randomIndex(availableNouns.length)];
}
